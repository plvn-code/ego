type Seed = Omit<Product, "id" | "currency" | "images" | "care" | "details"> & {
  details?: string[];
  care?: string[];
  /** Published colours that have no photos yet */
  more?: string;
};

let n = 0;
const P = ({ more, details = [], care = [], ...p }: Seed): Product => {
  n += 1;
  const count = counts[p.slug];
  if (!count) throw new Error(`No photos built for ${p.slug} — run scripts/build_images.py`);
  return {
    ...p,
    id: `eg${String(n).padStart(2, "0")}`,
    currency: "UAH",
    care,
    details: more ? [...details, `Також є: ${more} — фото надішлемо в Direct`] : details,
    images: Array.from({ length: count }, (_, i) => ({
      src: `/images/products/${p.slug}/${String(i + 1).padStart(2, "0")}.jpg`,
      alt: `${p.kind} ${p.name} — фото ${i + 1}`,
    })),
  };
};

